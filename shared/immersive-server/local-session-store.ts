import { createHash, randomBytes } from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
import { fixtureAnswer, type ApprovedAnswer, type BoundScope, type FixtureIntent } from './advisor.js';
import { SnapshotRegistry, type RoomSnapshot } from '../scene/room-model.js';

// Offline prototype only: process memory is neither durable nor shared across
// serverless instances. Callers must never expose create() as a public route.
export class LocalVoiceSessionStore {
  private readonly db = new DatabaseSync(':memory:');
  constructor(private readonly now: () => number = Date.now) {
    this.db.exec(`PRAGMA foreign_keys=ON;
      CREATE TABLE sessions (token_hash TEXT PRIMARY KEY, snapshot TEXT NOT NULL, generation TEXT NOT NULL, expires INTEGER NOT NULL);
      CREATE TABLE answers (id_hash TEXT PRIMARY KEY, token_hash TEXT NOT NULL REFERENCES sessions(token_hash) ON DELETE CASCADE, generation TEXT NOT NULL, intent TEXT NOT NULL, month INTEGER, expires INTEGER NOT NULL);`);
  }
  private hash(value: string): string { return createHash('sha256').update(value).digest('hex'); }
  private token(): string { return randomBytes(32).toString('base64url'); }
  private validToken(value: unknown): value is string { return typeof value === 'string' && /^[A-Za-z0-9_-]{43}$/.test(value); }
  private tx<T>(fn: () => T): T {
    this.db.exec('BEGIN IMMEDIATE');
    try { const result = fn(); this.db.exec('COMMIT'); return result; }
    catch (error) { this.db.exec('ROLLBACK'); throw error; }
  }
  /** Trusted local bootstrap only: snapshot must already be generated by the engine. */
  create(snapshot: RoomSnapshot, ttlMs: number): { token: string; generation: string } {
    if (!Number.isSafeInteger(ttlMs) || ttlMs < 1 || ttlMs > 15 * 60_000) throw new RangeError('invalid session lifetime');
    const token = this.token(); const generation = this.token();
    this.db.prepare('INSERT INTO sessions VALUES (?, ?, ?, ?)').run(this.hash(token), JSON.stringify(snapshot), generation, this.now() + ttlMs);
    return { token, generation };
  }
  private session(token: string): { snapshot: string; generation: string; expires: number } | null {
    if (!this.validToken(token)) return null;
    const row = this.db.prepare('SELECT snapshot, generation, expires FROM sessions WHERE token_hash = ? AND expires > ?').get(this.hash(token), this.now());
    return row ? row as unknown as { snapshot: string; generation: string; expires: number } : null;
  }
  /** A new turn invalidates every prior answer, including after switching back. */
  advance(token: string, expectedGeneration: string): string | null {
    return this.tx(() => {
      const s = this.session(token);
      if (!s || s.generation !== expectedGeneration) return null;
      const next = this.token();
      this.db.prepare('UPDATE sessions SET generation = ? WHERE token_hash = ?').run(next, this.hash(token));
      this.db.prepare('DELETE FROM answers WHERE token_hash = ?').run(this.hash(token));
      return next;
    });
  }
  revoke(token: string): boolean {
    if (!this.validToken(token)) return false;
    return Number(this.db.prepare('DELETE FROM sessions WHERE token_hash = ?').run(this.hash(token)).changes) === 1;
  }
  /** The stored recipe is resolved again through the deterministic engine claims. */
  private resolve(snapshot: RoomSnapshot, intent: FixtureIntent, month?: number): ApprovedAnswer | null {
    const registry = new SnapshotRegistry(); registry.add(snapshot);
    const scope: BoundScope = { sessionId: snapshot.ref.sessionId, profileRevision: snapshot.ref.profileRevision, snapshotKey: snapshot.key, pathId: snapshot.ref.pathId };
    const answer = fixtureAnswer(registry, scope, intent, month);
    return answer.ok ? answer.answer : null;
  }
  issueAnswer(token: string, generation: string, intent: FixtureIntent, month: number | undefined, signal: AbortSignal): { id: string; answer: ApprovedAnswer } | null {
    return this.tx(() => {
      const s = this.session(token);
      if (!s || s.generation !== generation || signal.aborted) return null;
      const answer = this.resolve(JSON.parse(s.snapshot) as RoomSnapshot, intent, month);
      if (!answer || signal.aborted) return null;
      const id = this.token();
      this.db.prepare('INSERT INTO answers VALUES (?, ?, ?, ?, ?, ?)').run(this.hash(id), this.hash(token), generation, intent, month ?? null, Math.min(s.expires, this.now() + 5 * 60_000));
      return { id, answer };
    });
  }
  loadAnswer(token: string, generation: string, id: string): ApprovedAnswer | null {
    if (!this.validToken(id)) return null;
    const s = this.session(token);
    if (!s || s.generation !== generation) return null;
    const row = this.db.prepare('SELECT intent, month FROM answers WHERE id_hash = ? AND token_hash = ? AND generation = ? AND expires > ?').get(this.hash(id), this.hash(token), generation, this.now());
    if (!row) return null;
    return this.resolve(JSON.parse(s.snapshot) as RoomSnapshot, row.intent as FixtureIntent, row.month === null ? undefined : Number(row.month));
  }
  /** Removes expired sessions and their answers; no background retention job. */
  purge(): void { this.tx(() => { this.db.prepare('DELETE FROM answers WHERE expires <= ?').run(this.now()); this.db.prepare('DELETE FROM sessions WHERE expires <= ?').run(this.now()); }); }
  close(): void { this.db.close(); }
}
